/**
 * Writes client/src/config.js from the environment.
 *
 * With no environment set it writes the local Supabase stack's
 * credentials, which are fixed because the local stack's JWT secret is
 * fixed. Point SUPABASE_URL and SUPABASE_ANON_KEY at a hosted project to
 * write that one instead.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const url = process.env.SUPABASE_URL ?? 'http://127.0.0.1:54321';
const key = process.env.SUPABASE_ANON_KEY
  ?? 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0';

// Where the edge functions are served.
//
// A hosted project runs its own functions, and the client finds them at
// the project's address - so there is nothing to point at and the value
// is null. A local stack serves the functions from the Node runner,
// because the Supabase edge runtime cannot read the function sources on a
// host whose SELinux policy has no docker rules.
const hosted = Boolean(process.env.SUPABASE_URL);
const functionsUrl = hosted ? 'null' : 'http://127.0.0.1:54399';

const body = `/**
 * Where the room backend lives.
 *
 * Generated by scripts/supabase-sync.js. The anon key is public by
 * definition - it is the key that is allowed to be in a browser. It can
 * read nothing: the quiz plan and the answer key sit behind row-level
 * security that the anon key cannot pass.
 */
export const config = {
  supabaseUrl: '${url}',
  supabaseAnonKey: '${key}',

  // Where the edge functions live. Null means "the Supabase project",
  // which is the hosted setup. Locally the functions are served by the
  // Node runner, because this host's SELinux policy keeps the Supabase
  // edge runtime from reading the function sources.
  functionsUrl: ${functionsUrl === 'null' ? 'null' : `'${functionsUrl}'`},
};
`;

await fs.writeFile(path.join(ROOT, 'client/src/config.js'), body);
console.log(`wrote client/src/config.js for ${url}`);
